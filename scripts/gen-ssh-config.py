#!/usr/bin/env python3
"""Generate SSH aliases for the whole gateway fleet from the backend registry.

Each gateway box has a UNIQUE reverse-SSH port in the prod `gateways` table
(assigned by the DB — see nemara-backend/scripts/apply_tunnel_registry_delta.sql).
This reads that table (port + the caregiver's email) and writes one SSH `Host`
block per box, so you reach any box off-LAN by NAME:

    ssh memoria-jane-patel-co        # -> ProxyJump memoria-relay -> its port -> box

Run it whenever you add/remove a box:  python3 scripts/gen-ssh-config.py
Needs SUPABASE_MGMT_TOKEN in the env (the sbp_… management token). The relay hop
`memoria-relay` must already exist in ~/.ssh/config (it does on the fleet Mac).
"""
import json
import os
import re
import sys
import urllib.request

PROJECT = os.environ.get("SUPABASE_PROJECT", "zgifmvjnggmgzvtnosnu")  # prod
TOKEN = os.environ.get("SUPABASE_MGMT_TOKEN", "")
SSH_DIR = os.path.expanduser("~/.ssh")
OUT = os.path.join(SSH_DIR, "config.d", "memoria-fleet")
MAIN = os.path.join(SSH_DIR, "config")
RELAY_HOST = "memoria-relay"          # must exist in ~/.ssh/config
BOX_USER = "potaton00b"

QUERY = (
    "SELECT g.tunnel_port, c.email "
    "FROM public.gateways g "
    "LEFT JOIN public.caregivers c ON c.id = g.caregiver_id "
    "WHERE g.tunnel_port IS NOT NULL ORDER BY g.tunnel_port"
)


def q(sql):
    req = urllib.request.Request(
        f"https://api.supabase.com/v1/projects/{PROJECT}/database/query",
        data=json.dumps({"query": sql}).encode(),
        headers={"Authorization": f"Bearer {TOKEN}",
                 "Content-Type": "application/json",
                 "User-Agent": "Mozilla/5.0"})
    return json.loads(urllib.request.urlopen(req).read())


def alias(email, port):
    base = email if email else f"gw-{port}"
    return "memoria-" + re.sub(r"[^a-z0-9]+", "-", base.lower()).strip("-")


def main():
    if not TOKEN:
        sys.exit("set SUPABASE_MGMT_TOKEN (the sbp_… management token) first")
    rows = q(QUERY)
    if isinstance(rows, dict) and rows.get("message"):
        sys.exit(f"query failed: {rows['message']}")
    lines = ["# GENERATED by scripts/gen-ssh-config.py — do not edit by hand.",
             "# One Host per gateway box; reach it off-LAN via the relay by name.\n"]
    for r in rows:
        port, email = r["tunnel_port"], r.get("email")
        a = alias(email, port)
        lines += [f"Host {a}   # {email or 'unassigned'}  (port {port})",
                  "    HostName localhost",
                  f"    Port {port}",
                  f"    User {BOX_USER}",
                  f"    ProxyJump {RELAY_HOST}",
                  "    StrictHostKeyChecking no",
                  "    UserKnownHostsFile /dev/null",
                  ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    # Make sure ~/.ssh/config pulls the generated file in (Include must precede
    # Host blocks, so we put it at the very top if it's not already there).
    inc = "Include config.d/memoria-fleet"
    cur = open(MAIN).read() if os.path.exists(MAIN) else ""
    if inc not in cur:
        with open(MAIN, "w") as f:
            f.write(inc + "\n\n" + cur)
    print(f"wrote {len([r for r in rows])} box alias(es) to {OUT}:")
    for r in rows:
        print(f"  ssh {alias(r.get('email'), r['tunnel_port'])}   -> port {r['tunnel_port']}")


if __name__ == "__main__":
    main()
